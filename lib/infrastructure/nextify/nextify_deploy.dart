/// The outcome of a Nextify launch.
class NextifyDeployResult {
  final NextifyInstance instance;
  final String jobId;
  final String? url;
  const NextifyDeployResult({
    required this.instance,
    required this.jobId,
    this.url,
  });
}

/// Generates a Nextify deploy bootstrap script that installs Node.js, builds
/// the app, and runs it as a systemd service behind an nginx reverse proxy on
/// port 80.
///
/// Two source modes:
///  * Git — [repoUrl]/[branch] are cloned at first boot (original behaviour).
///  * Local ([local] == true) — the files are already present at `/opt/app`
///    (pushed over SSH by [NextifyDeployer.launchLocal]); the script only
///    installs, builds, and serves.
///
/// The Dart template is a raw string using `__*__` placeholders, so shell `$`
/// variables never clash with Dart interpolation.
String nextifyNodeDeployScript({
  String? repoUrl,
  String? branch,
  int appPort = 3000,
  bool local = false,
}) {
  final varHead = local
      ? ''
      : 'REPO=${_bashSingleQuote(repoUrl ?? '')}\n'
          'BRANCH=${_bashSingleQuote(branch ?? '')}\n';
  final clone = local
      ? '# Files were pushed to /opt/app over SSH by Nexus-Studio (Option-B).\n'
      : '# Clone the repo (a specific branch when BRANCH is set).\n'
          'cd /opt\n'
          'if [ -n "\$BRANCH" ]; then\n'
          '  git clone --depth 1 --branch "\$BRANCH" "\$REPO" "\$APP_DIR"\n'
          'else\n'
          '  git clone --depth 1 "\$REPO" "\$APP_DIR"\n'
          'fi\n';
  const rest = r'''#!/bin/bash
# Generated by Nexus-Studio. Deploys a Node.js/Next.js app.
set -euxo pipefail
exec > >(tee /var/log/nexus_deploy.log) 2>&1
export DEBIAN_FRONTEND=noninteractive

__VAR_HEAD__APP_DIR=/opt/app
PORT=__PORT__

apt-get update
apt-get install -y ca-certificates curl git build-essential nginx
# Node.js 20 LTS via NodeSource.
curl -fsSL https://deb.nodesource.com/setup_20.x | bash -
apt-get install -y nodejs

__CLONE__cd "$APP_DIR"

# Install + build. Next.js needs `next build` before `next start`; a plain
# `npm start` project may have no build step (skip it if absent).
npm install
if node -e "process.exit(require('./package.json').scripts.build ? 0 : 1)" 2>/dev/null; then
  npm run build
fi

# Define an npm `serve` script (Next.js -> `next start -p PORT`; else the
# project's `start`) so the systemd unit is framework-agnostic.
node -e '
  const fs = require("fs");
  const p = require("./package.json");
  if (!p.scripts) p.scripts = {};
  const deps = Object.assign({}, p.dependencies || {}, p.devDependencies || {});
  const isNext = Object.keys(deps).includes("next");
  p.scripts.serve = isNext
    ? "next start -p " + process.env.PORT
    : (p.scripts.start || "npm start");
  fs.writeFileSync("./package.json", JSON.stringify(p, null, 2));
'

# Run the app as a systemd service (survives the boot script exiting).
cat > /etc/systemd/system/nexus-app.service <<EOF
[Unit]
Description=Nexus-Studio app
After=network.target

[Service]
WorkingDirectory=$APP_DIR
Environment=PORT=$PORT
ExecStart=/usr/bin/env npm run serve
Restart=always
RestartSec=3

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable nexus-app.service
systemctl restart nexus-app.service

# nginx: serve the app on port 80 (usually the only open one).
cat > /etc/nginx/sites-available/default <<EOF
server {
  listen 80 default_server;
  location / {
    proxy_pass http://127.0.0.1:$PORT;
    proxy_http_version 1.1;
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection "upgrade";
    proxy_set_header Host $host;
  }
}
EOF
systemctl reload nginx

# Best-effort: make sure 80 is open if a firewall is present.
command -v ufw >/dev/null 2>&1 && ufw allow 80/tcp || true
command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --permanent --add-port=80/tcp >/dev/null 2>&1 || true

echo "NEXUS_DEPLOY_DONE port=$PORT"
''';
  return rest
      .replaceAll('__VAR_HEAD__', varHead)
      .replaceAll('__CLONE__', clone)
      .replaceAll('__PORT__', '$appPort');
}

/// Quote a value for safe embedding in a single-quoted bash assignment.
String _bashSingleQuote(String s) => "'${s.replaceAll("'", "'\\''")}'";

/// Orchestrates a Nextify launch: create an instance running a generated
/// startup script, follow the provisioning job, then wait until the instance
/// has a public IP. Pure Dart (no Flutter), so it can be driven from the UI or
/// a CLI smoke test.
class NextifyDeployer {
  NextifyDeployer(this.client);
  final NextifyClient client;

  Future<NextifyDeployResult> launch({
    required String repoUrl,
    String? branch,
    required String instanceName,
    String machineType = 'sm1.s1-2',
    String region = 'us-west-1',
    String image = 'ubuntu-24.04',
    int appPort = 3000,
    Map<String, String> labels = const {},
    Duration jobTimeout = const Duration(minutes: 15),
    void Function(NextifyJob)? onProgress,
  }) async {
    final script = nextifyNodeDeployScript(
      repoUrl: repoUrl,
      branch: branch,
      appPort: appPort,
    );
    final created = await client.createInstance(
      name: instanceName,
      machineType: machineType,
      region: region,
      image: image,
      userData: script,
      labels: labels,
    );
    await client.waitForJob(
      created.jobId,
      timeout: jobTimeout,
      onProgress: onProgress,
    );

    // After the create job succeeds the instance is running and (usually) has
    // a public IP. Poll briefly for it.
    NextifyInstance inst = created.instance;
    String? ip =
        (inst.publicIp != null && inst.publicIp!.isNotEmpty) ? inst.publicIp : null;
    for (var i = 0; i < 20 && ip == null; i++) {
      inst = await client.getInstance(created.instance.id);
      ip = (inst.publicIp != null && inst.publicIp!.isNotEmpty)
          ? inst.publicIp
          : null;
      if (ip == null) {
        await Future<void>.delayed(const Duration(seconds: 3));
      }
    }
    return NextifyDeployResult(
      instance: inst,
      jobId: created.jobId,
      url: ip == null ? null : 'http://$ip/',
    );
  }

  /// Wait until [url] answers HTTP (2xx–4xx) or [timeout] elapses.
  Future<bool> waitForHttp(
    String url, {
    Duration timeout = const Duration(minutes: 6),
  }) async {
    final deadline = DateTime.now().add(timeout);
    final http = HttpClient();
    http.connectionTimeout = const Duration(seconds: 5);
    try {
      while (DateTime.now().isBefore(deadline)) {
        try {
          final req = await http.getUrl(Uri.parse(url));
          final resp = await req.close();
          await resp.drain();
          if (resp.statusCode >= 200 && resp.statusCode < 500) return true;
        } catch (_) {
          // Not listening yet — retry.
        }
        await Future<void>.delayed(const Duration(seconds: 4));
      }
    } finally {
      http.close(force: true);
    }
    return false;
  }

  /// Find an existing (non-deleted) instance by exact [name], or null.
  Future<NextifyInstance?> findByName(String name) async {
    final list = await client.listInstances();
    for (final i in list) {
      if (i.name == name && !i.isDeleted) return i;
    }
    return null;
  }

  /// Stop an instance.
  Future<String> stop(String id) => client.setDesiredStatus(id, 'stopped');

  /// Delete an instance — billing stops on delete.
  Future<String> delete(String id) => client.deleteInstance(id);

  /// The startup script's output (to diagnose a failed first-boot deploy).
  Future<String> setupLog(String id) => client.setupLog(id);

  // ── Option-B: push a local working tree over SSH (no git host) ─────────

  /// Deploys [localDir] (a materialised working tree) to a fresh blank VM:
  /// provisions an instance with our SSH key, opens the app port (and 22,
  /// scoped to our egress IP) on its security group, waits for SSH, pushes the
  /// tree to `/opt/app`, and kicks off the local-mode build script.
  ///
  /// Returns once the build has been kicked off; the caller then polls
  /// [waitForHttp] against the returned [NextifyDeployResult.url] and, on
  /// timeout, [fetchDeployLog] for the tail of the build log.
  Future<NextifyDeployResult> launchLocal({
    required String localDir,
    required String instanceName,
    String machineType = 'sm1.s1-2',
    String region = 'us-west-1',
    String image = 'ubuntu-24.04',
    int appPort = 3000,
    String sshKeyBaseDir = '',
    Map<String, String> labels = const {},
    Duration jobTimeout = const Duration(minutes: 15),
    void Function(NextifyJob)? onProgress,
  }) async {
    // 1. Our deploy key (generated once, reused).
    final key = await ensureSshKey(baseDir:
        sshKeyBaseDir.isNotEmpty ? sshKeyBaseDir : null);

    // 2. Register it with Nextify (find-or-create; the API keys by public key,
    //    so a repeat deploy with the same key reuses the existing id).
    final kid = await client.ensureSshKey(
      name: 'nexus-studio-deploy',
      publicKey: key.publicKey,
    );

    // 3. Provision a blank VM (no source/user_data — we do the rest over SSH).
    final created = await client.createInstance(
      name: instanceName,
      machineType: machineType,
      region: region,
      image: image,
      sshKeyIds: [kid],
      labels: labels,
    );
    await client.waitForJob(created.jobId, timeout: jobTimeout, onProgress: onProgress);

    // 4. Wait for the public IP + read the security group id(s).
    NextifyInstance inst = created.instance;
    String? ip;
    for (var i = 0; i < 40 && inst.publicIp == null; i++) {
      inst = await client.getInstance(created.instance.id);
      ip = inst.publicIp;
      if (ip == null || ip.isEmpty) {
        await Future<void>.delayed(const Duration(seconds: 3));
      }
    }
    if (ip == null || ip.isEmpty) {
      throw NextifyApiException(0, 'no_public_ip',
          'Instance ${created.instance.id} never got a public IP.');
    }

    // 5. Open the app port to the world; scope 22 to our egress IP for the push.
    //    Blank instances inherit the account's DEFAULT security group (their own
    //    `security_group_ids` stays empty), so find it to add rules to.
    String? sg;
    try {
      sg = (await client.defaultSecurityGroup())?.id;
    } catch (_) {}
    if (sg != null) {
      await client.addSecurityGroupRule(
        groupId: sg, protocol: 'tcp', portFrom: appPort, cidr: '0.0.0.0/0',
        description: 'nexus app',
      );
      final egress = await _myEgressIp() ?? '0.0.0.0/0';
      final cidr = egress.contains('/') ? egress : '$egress/32';
      await client.addSecurityGroupRule(
        groupId: sg, protocol: 'tcp', portFrom: 22, cidr: cidr,
        description: 'nexus deploy ssh',
      );
    }

    // 6. Wait until SSH accepts our key.
    final sshOk = await waitForSsh(privPath: key.privPath, host: ip);
    if (!sshOk) {
      throw NextifyApiException(0, 'ssh_unreachable',
          'Could not SSH to $ip within the timeout.');
    }

    // 7. Push the working tree to /opt/app.
    await pushDirectory(
      localDir: localDir,
      privPath: key.privPath,
      host: ip,
      remoteDir: '/opt/app',
    );

    // 8. Ship the build script + kick it off in the background.
    final script = nextifyNodeDeployScript(local: true, appPort: appPort);
    final scriptLocal = '${Directory.systemTemp.path}/nexus_setup_$appPort.sh';
    File(scriptLocal).writeAsStringSync(script);
    try {
      final scp = await scpFile(
        localPath: scriptLocal,
        privPath: key.privPath,
        host: ip,
        remotePath: '/home/ubuntu/nexus_setup.sh',
      );
      if (scp.exitCode != 0) {
        throw NextifyApiException(0, 'scp_setup_failed', '${scp.stderr}');
      }
      final kick = await sshRun(
        privPath: key.privPath,
        host: ip,
        command: 'chmod +x /home/ubuntu/nexus_setup.sh && '
            'nohup sudo bash /home/ubuntu/nexus_setup.sh '
            '> /home/ubuntu/nexus_launch.log 2>&1 < /dev/null & '
            'echo launched',
      );
      if (kick.exitCode != 0) {
        throw NextifyApiException(0, 'setup_kick_failed', '${kick.stderr}');
      }
    } finally {
      try {
        File(scriptLocal).deleteSync();
      } catch (_) {}
    }

    return NextifyDeployResult(
      instance: inst,
      jobId: created.jobId,
      url: 'http://$ip/',
    );
  }

  /// Fetch the tail of the VM's deploy log (to diagnose a build failure).
  Future<String> fetchDeployLog(String ip, {String user = 'ubuntu'}) async {
    final key = await ensureSshKey();
    return fetchRemote(
      privPath: key.privPath,
      host: ip,
      user: user,
      command: 'sudo tail -n 200 /var/log/nexus_deploy.log 2>/dev/null '
          '|| sudo cat /var/log/nexus_deploy.log 2>/dev/null',
    );
  }

  /// Our outbound IP (to scope the temporary 22 rule). Null on failure.
  Future<String?> _myEgressIp() async {
    final http = HttpClient();
    try {
      for (final host in const ['api.ipify.org', 'icanhazip.com']) {
        try {
          final req = await http.getUrl(Uri.https(host, '/'));
          final resp = await req.close();
          if (resp.statusCode == 200) {
            final b = await resp.transform(const Utf8Decoder()).join();
            final ip = b.trim();
            if (RegExp(r'^[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}$')
                    .hasMatch(ip)) {
              return ip;
            }
          }
        } catch (_) {}
      }
    } catch (_) {}
    return null;
  }
}
