import 'dart:async';
import 'dart:io';

import 'nextify_client.dart';
import 'nextify_models.dart';

/// The outcome of a Nextify launch.
class NextifyDeployResult {
  final NextifyInstance instance;
  final String jobId;
  final String? url;
  const NextifyDeployResult({
    required this.instance,
    required this.jobId,
    this.url,
  });
}

/// Generates a Nextify `user_data` startup script that installs Node.js,
/// clones a Git repo, builds it, and runs it as a systemd service behind an
/// nginx reverse proxy on port 80.
///
/// The script runs once, as root, at first boot (after the network is up). It
/// logs to `/var/log/nexus_deploy.log`. Keeping the app alive is delegated to
/// systemd (a `user_data` script itself must exit).
///
/// The Dart template is a raw string using `__REPO__`/`__BRANCH__`/`__PORT__`
/// placeholders, so shell `$` variables never clash with Dart interpolation.
String nextifyNodeDeployScript({
  required String repoUrl,
  String? branch,
  int appPort = 3000,
}) {
  const template = r'''#!/bin/bash
# Generated by Nexus-Studio. Deploys a Node.js/Next.js app from Git.
set -euxo pipefail
exec > >(tee /var/log/nexus_deploy.log) 2>&1
export DEBIAN_FRONTEND=noninteractive

REPO=__REPO__
BRANCH=__BRANCH__
APP_DIR=/opt/app
PORT=__PORT__

apt-get update
apt-get install -y ca-certificates curl git build-essential nginx
# Node.js 20 LTS via NodeSource.
curl -fsSL https://deb.nodesource.com/setup_20.x | bash -
apt-get install -y nodejs

# Clone the repo (a specific branch when BRANCH is set).
cd /opt
if [ -n "$BRANCH" ]; then
  git clone --depth 1 --branch "$BRANCH" "$REPO" "$APP_DIR"
else
  git clone --depth 1 "$REPO" "$APP_DIR"
fi
cd "$APP_DIR"

# Install + build. Next.js needs `next build` before `next start`; a plain
# `npm start` project may have no build step (skip it if absent).
npm install
if node -e "process.exit(require('./package.json').scripts.build ? 0 : 1)" 2>/dev/null; then
  npm run build
fi

# Define an npm `serve` script (Next.js -> `next start -p PORT`; else the
# project's `start`) so the systemd unit is framework-agnostic.
node -e '
  const fs = require("fs");
  const p = require("./package.json");
  if (!p.scripts) p.scripts = {};
  const deps = Object.assign({}, p.dependencies || {}, p.devDependencies || {});
  const isNext = Object.keys(deps).includes("next");
  p.scripts.serve = isNext
    ? "next start -p " + process.env.PORT
    : (p.scripts.start || "npm start");
  fs.writeFileSync("./package.json", JSON.stringify(p, null, 2));
'

# Run the app as a systemd service (survives the boot script exiting).
cat > /etc/systemd/system/nexus-app.service <<EOF
[Unit]
Description=Nexus-Studio app
After=network.target

[Service]
WorkingDirectory=$APP_DIR
Environment=PORT=$PORT
ExecStart=/usr/bin/env npm run serve
Restart=always
RestartSec=3

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable nexus-app.service
systemctl restart nexus-app.service

# nginx: serve the app on port 80 (usually the only open one).
cat > /etc/nginx/sites-available/default <<EOF
server {
  listen 80 default_server;
  location / {
    proxy_pass http://127.0.0.1:$PORT;
    proxy_http_version 1.1;
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection "upgrade";
    proxy_set_header Host $host;
  }
}
EOF
systemctl reload nginx

# Best-effort: make sure 80 is open if a firewall is present.
command -v ufw >/dev/null 2>&1 && ufw allow 80/tcp || true
command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --permanent --add-port=80/tcp >/dev/null 2>&1 || true

echo "NEXUS_DEPLOY_DONE port=$PORT"
''';
  return template
      .replaceAll('__REPO__', _bashSingleQuote(repoUrl))
      .replaceAll('__BRANCH__', _bashSingleQuote(branch ?? ''))
      .replaceAll('__PORT__', '$appPort');
}

/// Quote a value for safe embedding in a single-quoted bash assignment.
String _bashSingleQuote(String s) => "'${s.replaceAll("'", "'\\''")}'";

/// Orchestrates a Nextify launch: create an instance running a generated
/// startup script, follow the provisioning job, then wait until the instance
/// has a public IP. Pure Dart (no Flutter), so it can be driven from the UI or
/// a CLI smoke test.
class NextifyDeployer {
  NextifyDeployer(this.client);
  final NextifyClient client;

  Future<NextifyDeployResult> launch({
    required String repoUrl,
    String? branch,
    required String instanceName,
    String machineType = 'sm1.s1-2',
    String region = 'us-west-1',
    String image = 'ubuntu-24.04',
    int appPort = 3000,
    Map<String, String> labels = const {},
    Duration jobTimeout = const Duration(minutes: 15),
    void Function(NextifyJob)? onProgress,
  }) async {
    final script = nextifyNodeDeployScript(
      repoUrl: repoUrl,
      branch: branch,
      appPort: appPort,
    );
    final created = await client.createInstance(
      name: instanceName,
      machineType: machineType,
      region: region,
      image: image,
      userData: script,
      labels: labels,
    );
    await client.waitForJob(
      created.jobId,
      timeout: jobTimeout,
      onProgress: onProgress,
    );

    // After the create job succeeds the instance is running and (usually) has
    // a public IP. Poll briefly for it.
    NextifyInstance inst = created.instance;
    String? ip =
        (inst.publicIp != null && inst.publicIp!.isNotEmpty) ? inst.publicIp : null;
    for (var i = 0; i < 20 && ip == null; i++) {
      inst = await client.getInstance(created.instance.id);
      ip = (inst.publicIp != null && inst.publicIp!.isNotEmpty)
          ? inst.publicIp
          : null;
      if (ip == null) {
        await Future<void>.delayed(const Duration(seconds: 3));
      }
    }
    return NextifyDeployResult(
      instance: inst,
      jobId: created.jobId,
      url: ip == null ? null : 'http://$ip/',
    );
  }

  /// Wait until [url] answers HTTP (2xx–4xx) or [timeout] elapses.
  Future<bool> waitForHttp(
    String url, {
    Duration timeout = const Duration(minutes: 6),
  }) async {
    final deadline = DateTime.now().add(timeout);
    final http = HttpClient();
    http.connectionTimeout = const Duration(seconds: 5);
    try {
      while (DateTime.now().isBefore(deadline)) {
        try {
          final req = await http.getUrl(Uri.parse(url));
          final resp = await req.close();
          await resp.drain();
          if (resp.statusCode >= 200 && resp.statusCode < 500) return true;
        } catch (_) {
          // Not listening yet — retry.
        }
        await Future<void>.delayed(const Duration(seconds: 4));
      }
    } finally {
      http.close(force: true);
    }
    return false;
  }

  /// Find an existing (non-deleted) instance by exact [name], or null.
  Future<NextifyInstance?> findByName(String name) async {
    final list = await client.listInstances();
    for (final i in list) {
      if (i.name == name && !i.isDeleted) return i;
    }
    return null;
  }

  /// Stop an instance.
  Future<String> stop(String id) => client.setDesiredStatus(id, 'stopped');

  /// Delete an instance — billing stops on delete.
  Future<String> delete(String id) => client.deleteInstance(id);

  /// The startup script's output (to diagnose a failed first-boot deploy).
  Future<String> setupLog(String id) => client.setupLog(id);
}
